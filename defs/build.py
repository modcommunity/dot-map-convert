"""Builds rules/entity_defs.json, the class catalogue, from entity definition files and datamap dumps.

    heavy -- python3 -I tools/bsp/defs/build.py [--defs DIR] [--maps DIR] [--out FILE] [--check]

Inputs live outside the repository (`$DOTBSP_DEFS`, default `~/mapsrc/defs`, holding the
definition-file tree and `../dumps/<game>/dump_*.txt`). Only derived facts are written: class
names, key names with type, default and choice values, input and output names. Descriptions,
display names and the files themselves are never copied; the definition set carries no licence.
`--maps` scans bsp files for the classes real maps use and lists those the catalogue lacks.
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

ROOT = os.path.join(HERE, "..", "rules", "entity_defs.json")
IMPLICIT = "_cbaseentity_"
NOTICE = ("DERIVED DATA: class, key, input and output names, types and defaults only, generated by "
          "tools/bsp/defs/build.py from entity definition files and datamap dumps. Do not edit; regenerate.")

_TOK = re.compile(r'"((?:[^"\\]|\\.)*)"|([()\[\]=:,+@])|([^\s()\[\]=:,+@"]+)')


def tokens(text):
    """(kind, value) pairs: 's' string, 'p' punctuation, 'w' word; // comments dropped outside strings."""
    out = []
    for line in text.splitlines():
        i, in_s = 0, False
        while i < len(line):
            c = line[i]
            if c == '"':
                in_s = not in_s
            elif not in_s and line.startswith("//", i):
                line = line[:i]
                break
            i += 1
        out.append(line)
    out_t = []
    for m in _TOK.finditer("\n".join(out)):
        if m.group(1) is not None:
            out_t.append(("s", m.group(1)))
        elif m.group(2):
            out_t.append(("p", m.group(2)))
        else:
            out_t.append(("w", m.group(3)))
    return out_t


class _P:
    def __init__(self, toks):
        self.t, self.i = toks, 0

    def peek(self, k=0):
        return self.t[self.i + k] if self.i + k < len(self.t) else ("e", "")

    def next(self):
        v = self.peek()
        self.i += 1
        return v

    def is_p(self, ch, k=0):
        return self.peek(k) == ("p", ch)

    def skip_group(self, open_c, close_c):
        depth = 0
        while self.i < len(self.t):
            v = self.next()
            if v == ("p", open_c):
                depth += 1
            elif v == ("p", close_c):
                depth -= 1
                if depth <= 0:
                    return

    def args(self):
        """Words inside a balanced (...) group, strings included."""
        out, depth = [], 0
        while self.i < len(self.t):
            k, v = self.next()
            if (k, v) == ("p", "("):
                depth += 1
            elif (k, v) == ("p", ")"):
                depth -= 1
                if depth <= 0:
                    return out
            elif k in "sw":
                out.append(v)
        return out

    def string(self):
        parts = []
        while self.peek()[0] == "s":
            parts.append(self.next()[1])
            if self.is_p("+"):
                self.next()
        return "".join(parts)

    def part(self):
        """One ':'-separated value; "" when absent."""
        k, v = self.peek()
        if k == "s":
            return self.string()
        if k == "w" and not self.is_p("(", 1) and not self.is_p("[", 1) and v.lower() not in ("input", "output"):
            self.next()
            return v
        return ""


def _choice_body(p):
    """Values of a `= [ ... ]` body: (value, default flag)."""
    out = []
    p.next()
    while p.i < len(p.t) and not p.is_p("]"):
        k, v = p.next()
        if k == "w" and p.is_p(":"):
            p.next()
            p.part()
            flag = ""
            if p.is_p(":"):
                p.next()
                flag = p.part()
            out.append((v, flag))
        elif k == "s" and p.is_p(":"):
            val = v
            p.next()
            p.part()
            if p.is_p(":"):
                p.next()
                p.part()
            out.append((val, ""))
    p.next()
    return out


def _entry(p, cls):
    k, name = p.next()
    low = name.lower()
    if (k, name) == ("p", "@"):
        p.next()
        if p.is_p("["):
            p.skip_group("[", "]")
        return
    if low in ("input", "output") and p.peek()[0] == "w":
        io = low
        _k, nm = p.next()
        if p.is_p("["):
            p.skip_group("[", "]")
        typ = p.args()[0] if p.is_p("(") else ""
        while p.is_p(":"):
            p.next()
            p.part()
        cls[io + "s"].setdefault(nm.lower(), (nm, typ.lower()))
        return
    if k != "w":
        return
    if p.is_p("["):
        p.skip_group("[", "]")
    if not p.is_p("("):
        return
    a = p.args()
    typ = a[0].lower() if a else ""
    if p.peek() == ("w", "readonly"):
        p.next()
    parts = []
    while p.is_p(":"):
        p.next()
        parts.append(p.part())
    default = parts[1] if len(parts) > 1 else ""
    choices = []
    if p.is_p("="):
        p.next()
        if p.is_p("["):
            choices = _choice_body(p)
    if typ == "flags":
        default = str(sum(int(v) for v, f in choices if f.strip() == "1" and v.isdigit()))
        choices = []
    old = cls["keys"].get(low)
    rec = {"t": typ, "d": default}
    if choices:
        rec["c"] = [v for v, _f in choices]
    if old is None or (not old["d"] and default):
        cls["keys"][low] = rec


def parse_fgd(text, classes):
    """Add every @...Class in `text` to `classes` (name lowercase -> record)."""
    p = _P(tokens(text))
    while p.i < len(p.t):
        k, v = p.next()
        if (k, v) != ("p", "@"):
            continue
        kind = p.next()[1].lower()
        if not kind.endswith("class"):
            if p.is_p("("):
                p.args()
            elif p.peek()[0] == "s":
                p.next()
            if p.is_p("="):
                p.next()
                p.string()
            if p.is_p("["):
                p.skip_group("[", "]")
            continue
        bases = []
        while p.i < len(p.t) and not p.is_p("="):
            _k, prop = p.next()
            if p.is_p("("):
                a = p.args()
                if prop.lower() == "base":
                    bases += [b.lower() for b in a]
        p.next()
        name = p.next()[1]
        if p.is_p(":"):
            p.next()
            p.string()
        cls = {"base": kind == "baseclass", "solid": kind == "solidclass", "bases": bases,
               "keys": {}, "inputs": {}, "outputs": {}, "in": ["fgd"]}
        if p.is_p("["):
            p.next()
            while p.i < len(p.t) and not p.is_p("]"):
                before = p.i
                _entry(p, cls)
                if p.i == before:
                    p.next()
            p.next()
        old = classes.get(name.lower())
        if old is None:
            classes[name.lower()] = cls
        else:
            for f in ("keys", "inputs", "outputs"):
                for kk, vv in cls[f].items():
                    old[f].setdefault(kk, vv)
            old["bases"] += [b for b in bases if b not in old["bases"]]


def read_fgds(root):
    classes = {}
    for dp, dn, fn in os.walk(os.path.join(root, "HammerAddons", "fgd")):
        dn.sort()
        for f in sorted(fn):
            if f.lower().endswith(".fgd"):
                with open(os.path.join(dp, f), encoding="utf-8", errors="replace") as fh:
                    parse_fgd(fh.read(), classes)
    return classes


_HEAD = re.compile(r"^C\w+ - (\S+)\s*$")
_FIELD = re.compile(r"^- \S+ \(Offset -?\d+\) \(([^)]*)\)\(\d+ Bytes\)(?: - (.*\S))?\s*$")


def read_datamaps(path):
    """classname (lowercase) -> {'keys', 'inputs', 'outputs'} sets of the names the engine sees."""
    out, cur = {}, None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = _HEAD.match(line)
            if m:
                cur = out.setdefault(m.group(1).lower(), {"keys": set(), "inputs": {}, "outputs": {}})
                continue
            m = _FIELD.match(line)
            if m and cur is not None and m.group(2):
                flags = m.group(1).split("|")
                n = m.group(2)
                if "Input" in flags:
                    cur["inputs"].setdefault(n.lower(), n)
                elif "Output" in flags:
                    cur["outputs"].setdefault(n.lower(), n)
                elif "Key" in flags:
                    cur["keys"].add(n.lower())
    return out


def read_class_list(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return {m.group(1).lower() for m in (_HEAD.match(x) for x in fh) if m}


def flatten(classes, name, seen=None):
    """(keys, inputs, outputs) of a class with its bases, the implicit base first."""
    seen = seen if seen is not None else set()
    keys, ins, outs = {}, {}, {}
    if name in seen or name not in classes:
        return keys, ins, outs
    seen.add(name)
    c = classes[name]
    chain = ([IMPLICIT] if name != IMPLICIT else []) + c["bases"]
    for b in chain:
        bk, bi, bo = flatten(classes, b, seen)
        keys.update(bk), ins.update(bi), outs.update(bo)
    keys.update({k: {"t": "", "d": ""} for k in c.get("extra", ())})
    keys.update(c["keys"]), ins.update(c["inputs"]), outs.update(c["outputs"])
    return keys, ins, outs


def merge_dumps(classes, dumps):
    """Add what each dump saw: a class only the engine knows, and fields the definitions lack."""
    for game, dm in sorted(dumps.items()):
        for name in sorted(dm["listed"] | set(dm["maps"])):
            if name not in classes:
                classes[name] = {"base": False, "solid": False, "bases": [], "keys": {}, "inputs": {},
                                 "outputs": {}, "in": []}
            c = classes[name]
            if game not in c["in"]:
                c["in"].append(game)
            seen = dm["maps"].get(name)
            if not seen:
                continue
            keys, ins, outs = flatten(classes, name)
            for k in sorted(seen["keys"]):
                if k not in keys:
                    c.setdefault("extra", set()).add(k)
            for k, n in sorted(seen["inputs"].items()):
                if k not in ins:
                    c["inputs"][k] = (n, "")
            for k, n in sorted(seen["outputs"].items()):
                if k not in outs:
                    c["outputs"][k] = (n, "")


def scan_maps(root):
    """classname (lowercase) -> number of distinct maps using it, over every loose bsp under `root`.

    Archives are skipped (their maps are extracted beside them), as are `defs`, `dumps` and the
    content store; identical files count once.
    """
    import hashlib
    from dotbsp import reader
    counts, bad, seen = {}, 0, set()
    for dp, dn, fn in os.walk(root):
        dn[:] = sorted(d for d in dn if not (dp == root and d in ("defs", "dumps", "store", "tools")))
        for f in sorted(fn):
            if not f.lower().endswith(".bsp"):
                continue
            with open(os.path.join(dp, f), "rb") as fh:
                data = fh.read()
            h = hashlib.sha1(data).hexdigest()
            if h in seen:
                continue
            seen.add(h)
            try:
                bsp = reader.Bsp(os.path.join(dp, f), data=data).load()
            except (ValueError, OSError):
                bad += 1
                continue
            for c in {e.get("classname", "").lower() for e in bsp.entities} | ({"prop_static"} if bsp.static_props() else set()):
                if c:
                    counts[c] = counts.get(c, 0) + 1
    return counts, bad, len(seen)


def build(defs_root, maps_root=None):
    classes = read_fgds(defs_root)
    dumps = {}
    dump_root = os.path.join(os.path.dirname(defs_root.rstrip("/")), "dumps")
    for game in sorted(os.listdir(dump_root)) if os.path.isdir(dump_root) else []:
        d = os.path.join(dump_root, game)
        dm, cl = os.path.join(d, "dump_datamaps.txt"), os.path.join(d, "dump_classes.txt")
        if os.path.isfile(dm) or os.path.isfile(cl):
            dumps[game] = {"maps": read_datamaps(dm) if os.path.isfile(dm) else {},
                           "listed": read_class_list(cl) if os.path.isfile(cl) else set()}
    merge_dumps(classes, dumps)
    doc = {"_notice": NOTICE, "dumps": sorted(dumps), "bases": {}, "classes": {}}
    for name in sorted(classes):
        c = classes[name]
        rec = {}
        if c["bases"]:
            rec["bases"] = c["bases"]
        if c["solid"]:
            rec["solid"] = True
        for f in ("keys", "inputs", "outputs"):
            if c[f]:
                rec[f] = ({k: [v["t"], v["d"]] + ([v["c"]] if "c" in v else []) for k, v in sorted(c[f].items())} if f == "keys"
                          else {n: t for _k, (n, t) in sorted(c[f].items())})
        if c.get("extra"):
            rec["extra"] = sorted(c["extra"])
        rec["in"] = c["in"]
        doc["bases" if c["base"] else "classes"][name] = rec
    if maps_root:
        counts, bad, n = scan_maps(maps_root)
        doc["map_classes"] = {k: counts[k] for k in sorted(counts)}
        doc["unknown"] = sorted(k for k in counts if k not in doc["classes"] and k not in doc["bases"])
        doc["maps_scanned"] = n
        doc["maps_unreadable"] = bad
    return doc


def dumps_json(doc):
    """One class per line: small diffs, readable."""
    lines = ["{"]
    items = list(doc.items())
    for i, (k, v) in enumerate(items):
        end = "," if i < len(items) - 1 else ""
        if isinstance(v, dict) and k in ("bases", "classes", "map_classes"):
            lines.append('"%s": {' % k)
            sub = list(v.items())
            for j, (n, r) in enumerate(sub):
                lines.append("%s: %s%s" % (json.dumps(n), json.dumps(r, separators=(",", ":"), sort_keys=True),
                                           "," if j < len(sub) - 1 else ""))
            lines.append("}" + end)
        else:
            lines.append('"%s": %s%s' % (k, json.dumps(v, separators=(",", ":")), end))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--defs", default=os.environ.get("DOTBSP_DEFS", os.path.expanduser("~/mapsrc/defs")))
    ap.add_argument("--maps", default=os.path.expanduser("~/mapsrc"), help="directory of bsp files to scan ('' to skip)")
    ap.add_argument("--out", default=os.path.normpath(ROOT))
    ap.add_argument("--check", action="store_true", help="fail when --out differs from a fresh build")
    a = ap.parse_args()
    text = dumps_json(build(a.defs, a.maps or None))
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("entity_defs.json is %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    d = json.loads(text)
    print("%d classes, %d bases, %d unknown (of %d map classes); %d bytes" % (
        len(d["classes"]), len(d["bases"]), len(d.get("unknown", [])), len(d.get("map_classes", {})), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
